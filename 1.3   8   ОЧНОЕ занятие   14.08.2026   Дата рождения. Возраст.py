

"""
Напишите программу, которая:
1. Запрашивает у пользователя дату рождения в формате DD. MM. YYYY
2. Вычисляет возраст пользователя на текущую дату ().
3. Выводит результат в формате: "Вам {возраст} лет (год / года)".
4. Обработайте случай, если пользователь ввел некорректную дату (например 31.02.2000)

"""

import datetime

try:
    bthd_str = input("Введите дату рождения в формате ДД.ММ.ГГГГ: ")
    bthd = datetime.datetime.strptime(bthd_str, "%d.%m.%Y")             # Убрали пробелы из формата: теперь подойдёт 20.07.1995

    now = datetime.datetime.now()

    age = now.year - bthd.year                                                 # Сначала считаем возраст как разницу лет

    if (now.month, now.day) < (bthd.month, bthd.day):                          # Корректируем, если день рождения ещё не наступил в этом году
        age -= 1
    if age % 10 == 1 and age % 100 != 11:                                      # Склонение слова «год» по правилам русского языка
        word = "год"
    elif age % 10 in (2, 3, 4) and age % 100 not in (12, 13, 14):
        word = "года"
    else:
        word = "лет"

    print(age)
    print(f'Вам {age} {word}')

except ValueError:
    print("Ошибка даты")